#!/usr/bin/env -S deno run -A
// Echelon Analytics — builds the Rust hot path module and embeds it.
//
// Compiles hotpath/ to wasm32-unknown-unknown and writes the binary, base64
// encoded, to lib/hotpath-wasm.ts. That file is committed, so running or
// deploying Echelon needs no Rust toolchain; only changing hotpath/src does.
//
// Usage: deno task build:hotpath
//   (needs cargo and `rustup target add wasm32-unknown-unknown`)

const here = new URL(".", import.meta.url);
const build = await new Deno.Command("cargo", {
  args: [
    "build",
    "--release",
    "--locked",
    "--target",
    "wasm32-unknown-unknown",
  ],
  cwd: here,
  stdout: "inherit",
  stderr: "inherit",
}).output();
if (!build.success) Deno.exit(build.code);

const wasm = await Deno.readFile(
  new URL(
    "target/wasm32-unknown-unknown/release/echelon_hotpath.wasm",
    here,
  ),
);
// Fail here, not at server start, if the binary does not load.
new WebAssembly.Instance(new WebAssembly.Module(wasm));

let bin = "";
for (let i = 0; i < wasm.length; i += 0x8000) {
  bin += String.fromCharCode(...wasm.subarray(i, i + 0x8000));
}
const out = new URL("../lib/hotpath-wasm.ts", here);
await Deno.writeTextFile(
  out,
  `// GENERATED by hotpath/build.ts from hotpath/src — do not edit.
// Rebuild with: deno task build:hotpath
export const HOTPATH_WASM_BASE64 =
  "${btoa(bin)}";
`,
);
console.log(`[hotpath] wrote ${out.pathname} (${wasm.length} bytes of WASM)`);
